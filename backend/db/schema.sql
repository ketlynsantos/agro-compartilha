-- 1. Limpeza
BEGIN
   FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('AVALIACAO', 'RESERVA', 'IMPLEMENTO_AGRICOLA',
                                  'MAQUINA_MOTORIZADA', 'EQUIPAMENTO', 'PRODUTOR')) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
   END LOOP;
END;
