-- 2. Tabelas

CREATE TABLE produtor (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR2(100) NOT NULL,
    documento   VARCHAR2(14)  NOT NULL,
    telefone    VARCHAR2(11)  NOT NULL,
    municipio   VARCHAR2(80)  NOT NULL,
    senha_hash  VARCHAR2(200) NOT NULL,
    CONSTRAINT pk_produtor PRIMARY KEY (id),
    CONSTRAINT uk_produtor_documento UNIQUE (documento),
    CONSTRAINT ck_produtor_documento CHECK (LENGTH(documento) IN (11, 14))
);

-- disponivel = 0: dono pausou os empréstimos | ativo = 0: equipamento removido (exclusão lógica)
CREATE TABLE equipamento (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    produtor_id   NUMBER        NOT NULL,
    nome          VARCHAR2(100) NOT NULL,
    descricao     VARCHAR2(500),
    tipo          VARCHAR2(20)  NOT NULL,
    valor_diaria  NUMBER(10,2),
    disponivel    NUMBER(1)     DEFAULT 1 NOT NULL,
    ativo         NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_equipamento PRIMARY KEY (id),
    CONSTRAINT fk_equipamento_produtor FOREIGN KEY (produtor_id) REFERENCES produtor (id),
    CONSTRAINT ck_equipamento_tipo CHECK (tipo IN ('MOTORIZADA', 'IMPLEMENTO')),
    CONSTRAINT ck_equipamento_valor CHECK (valor_diaria IS NULL OR valor_diaria >= 0),
    CONSTRAINT ck_equipamento_disponivel CHECK (disponivel IN (0, 1)),
    CONSTRAINT ck_equipamento_ativo CHECK (ativo IN (0, 1))
);

CREATE TABLE maquina_motorizada (
    equipamento_id    NUMBER       NOT NULL,
    potencia_cv       NUMBER(6,1)  NOT NULL,
    tipo_combustivel  VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_maquina_motorizada PRIMARY KEY (equipamento_id),
    CONSTRAINT fk_maquina_equipamento FOREIGN KEY (equipamento_id) REFERENCES equipamento (id),
    CONSTRAINT ck_maquina_potencia CHECK (potencia_cv > 0),
    CONSTRAINT ck_maquina_combustivel CHECK (tipo_combustivel IN ('DIESEL', 'GASOLINA'))
);

CREATE TABLE implemento_agricola (
    equipamento_id   NUMBER        NOT NULL,
    tipo_implemento  VARCHAR2(50)  NOT NULL,
    compatibilidade  VARCHAR2(200),
    CONSTRAINT pk_implemento_agricola PRIMARY KEY (equipamento_id),
    CONSTRAINT fk_implemento_equipamento FOREIGN KEY (equipamento_id) REFERENCES equipamento (id)
);

-- Tabela associativa N:N entre PRODUTOR (solicitante) e EQUIPAMENTO
-- valor_total é fixado no momento do pedido (diária x dias)
CREATE TABLE reserva (
    id                       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    produtor_solicitante_id  NUMBER       NOT NULL,
    equipamento_id           NUMBER       NOT NULL,
    data_inicio              DATE         NOT NULL,
    data_fim                 DATE         NOT NULL,
    status                   VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    valor_total              NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_reserva PRIMARY KEY (id),
    CONSTRAINT fk_reserva_solicitante FOREIGN KEY (produtor_solicitante_id) REFERENCES produtor (id),
    CONSTRAINT fk_reserva_equipamento FOREIGN KEY (equipamento_id) REFERENCES equipamento (id),
    CONSTRAINT ck_reserva_status CHECK (status IN ('PENDENTE', 'APROVADA', 'REJEITADA', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_reserva_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_reserva_valor CHECK (valor_total >= 0)
);

CREATE TABLE avaliacao (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reserva_id      NUMBER        NOT NULL,
    avaliador_id    NUMBER        NOT NULL,
    avaliado_id     NUMBER        NOT NULL,
    nota            NUMBER(1)     NOT NULL,
    comentario      VARCHAR2(500),
    data_avaliacao  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_avaliacao PRIMARY KEY (id),
    CONSTRAINT fk_avaliacao_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT fk_avaliacao_avaliador FOREIGN KEY (avaliador_id) REFERENCES produtor (id),
    CONSTRAINT fk_avaliacao_avaliado FOREIGN KEY (avaliado_id) REFERENCES produtor (id),
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_partes CHECK (avaliador_id <> avaliado_id),
    CONSTRAINT uk_avaliacao_reserva_avaliador UNIQUE (reserva_id, avaliador_id)
);

